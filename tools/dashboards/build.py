def level_forecast(valid, level):
    return f"""const now = Date.now();
const a = entity.attributes;
const valid = hass.states['{valid}'];
if (['unknown', 'unavailable'].includes(entity.state) ||
    (!a.refreshing && (valid?.state !== 'on' || !(Date.parse(a.valid_until) > now)))) return [];
const left = Math.max(now, start.getTime());
const coverage = Date.parse(valid?.attributes?.coverage_end);
const right = Math.min(end.getTime(), Number.isFinite(coverage) ? coverage : end.getTime());
if (right <= left) return [];
const points = new Map([[left, 0], [right, 0]]);
for (const row of (a.outlook || [])) {{
  const from = Math.max(left, Date.parse(row.start));
  const to = Math.min(right, Date.parse(row.end));
  if (!(to > from) || !['BOOST', 'CHEAP', 'NORMAL', 'LIMIT'].includes(row.level)) continue;
  const value = row.level === '{level}' ? 1 : 0;
  points.set(from, value);
  points.set(to - 1, value);
  points.set(to, 0);
}}
return [...points].sort((a, b) => a[0] - b[0]);
"""


