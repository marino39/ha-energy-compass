def dump(value):
    return HEADER + yaml.safe_dump(
        value, sort_keys=False, allow_unicode=True, width=120
    )


def outputs():
    return {
        OUT / "plan_chart.yaml": dump(plan_section()),
        OUT / "consumer_compass_chart.yaml": dump(consumer_section()),
        OUT / "deye_controller.yaml": dump(controller_section()),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed examples are stale"
    )
    parser.add_argument(
        "--print",
        choices=list(SECTIONS),
        help="print one section instead of writing the examples",
    )
    parser.add_argument("--lang", choices=list(LABELS), default="en")
    parser.add_argument(
        "--entity",
        action="append",
        default=[],
        metavar="ROLE=ENTITY_ID",
        help=f"roles: {', '.join(ENTITIES)}",
    )
    parser.add_argument(
        "--capacity",
        type=float,
        default=CAPACITY_KWH,
        help="battery capacity in kWh (plan chart)",
    )
    args = parser.parse_args(argv)
    if args.print:
        entities = ENTITIES | dict(item.split("=", 1) for item in args.entity)
        unknown = set(entities) - set(ENTITIES)
        if unknown:
            parser.error(f"unknown role: {', '.join(sorted(unknown))}")
        kwargs = {"capacity": args.capacity} if args.print == "plan" else {}
        sys.stdout.write(dump(SECTIONS[args.print](entities, args.lang, **kwargs)))
        return 0
    stale = [
        path
        for path, text in outputs().items()
        if not path.exists() or path.read_text() != text
    ]
    if args.check:
        for path in stale:
            print(
                f"stale: {path.relative_to(REPO)} - run python tools/dashboards/build.py",
                file=sys.stderr,
            )
        return 1 if stale else 0
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
